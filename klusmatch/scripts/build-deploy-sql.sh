#!/usr/bin/env bash
# Regenerates deploy/01-schema.sql (all migrations) and deploy/02-demo-data.sql (demo seed)
# from db/migrations and scripts/seed-demo.ts. Needs a local Postgres where the current user can
# create databases (set PGADMIN_URL / DB_BASE to override). Run after adding a migration.
set -euo pipefail
cd "$(dirname "$0")/.."
BASE=${DB_BASE:-postgres://klusmatch:klusmatch@localhost:5432}
TMPDB=klusmatch_bundle_$$
psql -q "$BASE/postgres" -c "create database $TMPDB"
trap 'psql -q "$BASE/postgres" -c "drop database if exists $TMPDB" >/dev/null' EXIT
DATABASE_URL=$BASE/$TMPDB npx tsx scripts/migrate.ts >/dev/null
DATABASE_URL=$BASE/$TMPDB APP_ENV=demo AI_PROVIDER=rules INLINE_WORKER=false npx tsx scripts/seed-demo.ts >/dev/null

{
  echo "-- KlusMatch AI — database schema (all migrations). Paste into the Supabase SQL editor and run once."
  echo "-- Generated by scripts/build-deploy-sql.sh from db/migrations; do not edit by hand."
  echo "begin;"
  echo "create table if not exists schema_migrations (name text primary key, applied_at timestamptz not null default now());"
  for f in db/migrations/*.sql; do
    echo; echo "-- ── $(basename "$f") ──"; cat "$f"
    echo "insert into schema_migrations (name) values ('$(basename "$f")');"
  done
  cat <<'SQL'

-- Private storage bucket for uploaded photos (Supabase only; skipped on plain Postgres).
do $$ begin
  if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
    insert into storage.buckets (id, name, public) values ('klusmatch-media', 'klusmatch-media', false) on conflict (id) do nothing;
  end if;
end $$;
commit;
SQL
} > deploy/01-schema.sql

{
  echo "-- KlusMatch AI — DEMO DATA ONLY (accounts @demo.klusmatch.test, password: demo-wachtwoord-2026)."
  echo "-- Run after 01-schema.sql, and only in a test/demo project. Never in production."
  echo "begin;"
  pg_dump "$BASE/$TMPDB" --data-only --column-inserts --no-owner --no-privileges \
    --exclude-table-data=schema_migrations --exclude-table-data=categories --exclude-table-data=matching_rules \
    --exclude-table-data=background_jobs --exclude-table-data=rate_limits --exclude-table-data=sessions 2>/dev/null \
    | grep -vE '^(SET |SELECT pg_catalog\.set_config|--|$|\\(un)?restrict )' # keep setval(); drop psql-only meta-commands
  echo "commit;"
} > deploy/02-demo-data.sql
# Self-check: load both files into a fresh database and insert into every serial table.
CHECKDB=klusmatch_check_$$
psql -q "$BASE/postgres" -c "create database $CHECKDB"
trap 'psql -q "$BASE/postgres" -c "drop database if exists $TMPDB" >/dev/null; psql -q "$BASE/postgres" -c "drop database if exists $CHECKDB" >/dev/null' EXIT
psql -q -v ON_ERROR_STOP=1 "$BASE/$CHECKDB" -f deploy/01-schema.sql >/dev/null
psql -q -v ON_ERROR_STOP=1 "$BASE/$CHECKDB" -f deploy/02-demo-data.sql >/dev/null
psql -q -v ON_ERROR_STOP=1 "$BASE/$CHECKDB" -c "insert into audit_log (action, entity_type) values ('deploy.check', 'system')" \
  -c "insert into job_events (job_id, kind) select id, 'published' from jobs limit 1" >/dev/null
echo "self-check passed (fresh load + new inserts)"
wc -l deploy/01-schema.sql deploy/02-demo-data.sql
